#!/usr/bin/env bash
# SLBZT for Linux: ONE script to install or update, on any supported CPU.
#   Install:  curl -fsSL https://github.com/wmsid/trying/raw/main/bin/slbzt_linux_setup.sh | sudo bash -s -- <SETUP_KEY>
#   Update:   curl -fsSL https://github.com/wmsid/trying/raw/main/bin/slbzt_linux_setup.sh | sudo bash
# (or download it and run: sudo bash slbzt_linux_setup.sh [SETUP_KEY])
# The same template serves Linux and macOS; it checks it is running on the OS it was made for.
# It detects the CPU, downloads the matching build (checksum-verified) and runs its install.sh, which
# does a fresh install when the machine is new, or an in-place update that keeps the config and peer.
# Generated by scripts/build.sh; the values below are filled in at build time.
set -euo pipefail
BRAND=slbzt
VERSION=1.1.0
BASE_URL=https://github.com/wmsid/trying/raw/main/bin

[ "$(id -u)" = 0 ] || { echo "Run as root, e.g.: sudo bash $0 [SETUP_KEY]"; exit 1; }
OS=linux
case "$OS:$(uname -s)" in
  linux:Linux|macos:Darwin) ;;
  *) echo "This script is for Linux; this computer runs $(uname -s)."; exit 1 ;;
esac

if [ "$OS" = macos ]; then
  # Apple Silicon reports x86_64 when the shell runs under Rosetta, so ask the hardware
  if [ "$(sysctl -n hw.optional.arm64 2>/dev/null || echo 0)" = 1 ]; then ARCH=arm64; else ARCH=amd64; fi
  PKG_OS=darwin
  sha256_check() { shasum -a 256 -c -; }
else
  case "$(uname -m)" in
    x86_64|amd64)          ARCH=amd64 ;;
    aarch64|arm64)         ARCH=arm64 ;;
    armv6*|armv7*|armhf)   ARCH=arm ;;
    i386|i486|i586|i686)   ARCH=386 ;;
    *) echo "Unsupported CPU: $(uname -m)"; exit 1 ;;
  esac
  PKG_OS=linux
  sha256_check() { sha256sum -c --quiet -; }
fi

if command -v curl >/dev/null; then fetch() { curl -fsSL -o "$2" "$1"; }
elif command -v wget >/dev/null; then fetch() { wget -qO "$2" "$1"; }
else echo "Needs curl or wget."; exit 1; fi

PKG="${BRAND}_${VERSION}_${PKG_OS}_${ARCH}"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
echo "Downloading $PKG ..."
fetch "$BASE_URL/$PKG.tar.gz" "$TMP/$PKG.tar.gz"
fetch "$BASE_URL/SHA256SUMS" "$TMP/SHA256SUMS"
( cd "$TMP" && grep " $PKG.tar.gz\$" SHA256SUMS | sha256_check >/dev/null ) || { echo "Checksum mismatch, aborting."; exit 1; }
tar -C "$TMP" -xzf "$TMP/$PKG.tar.gz"
"$TMP/$PKG/install.sh" "$@"
